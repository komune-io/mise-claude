#[test]
fn file_lockfile_store_save_then_load_roundtrips() {
    let project = TempDir::new().unwrap();
    let store = FileLockfileStore::new(project.path());

    let mut lockfile = Lockfile::new();
    lockfile.set(
        "mcp",
        "context7",
        LockedTool {
            package: Some("@upstash/context7-mcp".to_string()),
            version: "2.1.4".to_string(),
            integrity: None,
            resolved_at: None,
            skills: None,
        },
    );
    store.save(&lockfile).unwrap();

    let loaded = store.load().unwrap();
    let entry = loaded.get("mcp", "context7").unwrap();
    assert_eq!(entry.version, "2.1.4");
}

#[test]
fn file_lockfile_store_snapshot_preserves_exact_bytes() {
    let project = TempDir::new().unwrap();
    let original =
        "# Auto-generated by chord. Do not edit.\n\n[mcp.context7]\nversion = \"2.1.4\"\n";
    fs::write(project.path().join("chord.lock"), original).unwrap();

    let store = FileLockfileStore::new(project.path());
    let snap = store.snapshot().unwrap();

    let mut lockfile = store.load().unwrap();
    lockfile.set(
        "mcp",
        "memory",
        LockedTool {
            package: Some("memory".to_string()),
            version: "1.0.0".to_string(),
            integrity: None,
            resolved_at: None,
            skills: None,
        },
    );
    store.save(&lockfile).unwrap();
    assert_ne!(
        fs::read(project.path().join("chord.lock")).unwrap(),
        original.as_bytes()
    );

    store.restore(&snap).unwrap();
    assert_eq!(
        fs::read(project.path().join("chord.lock")).unwrap(),
        original.as_bytes()
    );
}

